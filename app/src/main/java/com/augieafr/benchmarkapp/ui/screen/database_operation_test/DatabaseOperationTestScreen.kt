@Composable
fun DatabaseOperationTestScreen(
    modifier: Modifier = Modifier
) {
    val context = LocalContext.current
    val viewModel: DatabaseOperationTestViewModel = viewModel {
        DatabaseOperationTestViewModel(context.applicationContext as android.app.Application)
    }
    val benchmarkResults by viewModel.benchmarkResults.collectAsState()
    val totalNotes by viewModel.totalNotes.collectAsState()
    val isLoading by viewModel.isLoading.collectAsState()
    val errorMessage by viewModel.errorMessage.collectAsState()
    val randomNotesCount by viewModel.randomNotesCount.collectAsState()
    val notesGenerated by viewModel.notesGenerated.collectAsState()

    Column(
        modifier = modifier
            .fillMaxSize()
            .padding(16.dp),
        verticalArrangement = Arrangement.spacedBy(16.dp)
    ) {
        // Header Section
        DatabaseHeaderSection(
            totalNotes = totalNotes,
            randomNotesCount = randomNotesCount,
            notesGenerated = notesGenerated
        )

        // Notes Count Input Section
        NotesCountInputSection(
            notesCount = randomNotesCount,
            onNotesCountChange = { viewModel.updateRandomNotesCount(it) },
            onGenerateNotes = { viewModel.generateRandomNotes() },
            isLoading = isLoading
        )

        // Action Buttons
        DatabaseActionButtons(
            onRunBenchmark = { viewModel.runDatabaseBenchmark() },
            isLoading = isLoading,
            isReady = notesGenerated
        )

        // Error Message
        errorMessage?.let { error ->
            ErrorCard(
                message = error,
                onDismiss = { viewModel.clearError() }
            )
        }

        // Benchmark Results
        if (benchmarkResults.isNotEmpty()) {
            BenchmarkResultsSection(
                results = benchmarkResults,
                modifier = Modifier.weight(1f)
            )
        } else if (!isLoading) {
            EmptyStateSection()
        }

        // Loading Indicator
        if (isLoading) {
            LoadingSection()
        }
    }
}

@Composable
private fun DatabaseHeaderSection(
    totalNotes: Int,
    randomNotesCount: Int,
    notesGenerated: Boolean
) {
    Card(
        modifier = Modifier.fillMaxWidth(),
        colors = CardDefaults.cardColors(
            containerColor = MaterialTheme.colorScheme.primaryContainer
        )
    ) {
        Row(
            modifier = Modifier
                .fillMaxWidth()
                .padding(16.dp),
            horizontalArrangement = Arrangement.SpaceBetween,
            verticalAlignment = Alignment.CenterVertically
        ) {
            Column {
                Text(
                    text = "Database Status",
                    style = MaterialTheme.typography.titleMedium,
                    fontWeight = FontWeight.Bold
                )
                Text(
                    text = "Total Notes: $totalNotes",
                    style = MaterialTheme.typography.bodyLarge,
                    color = MaterialTheme.colorScheme.onPrimaryContainer
                )

                Spacer(modifier = Modifier.height(4.dp))

                // Benchmark Status
                val statusText = if (notesGenerated) {
                    "Ready to benchmark ($randomNotesCount notes prepared)"
                } else {
                    "Not ready - Please generate notes first"
                }
                val statusColor = if (notesGenerated) {
                    MaterialTheme.colorScheme.primary
                } else {
                    MaterialTheme.colorScheme.error
                }

                Text(
                    text = statusText,
                    style = MaterialTheme.typography.bodyMedium,
                    color = statusColor,
                    fontWeight = if (notesGenerated) FontWeight.Medium else FontWeight.Normal
                )
            }

            Icon(
                imageVector = Icons.AutoMirrored.Default.List,
                contentDescription = "Database",
                tint = MaterialTheme.colorScheme.primary
            )
        }
    }
}

@Composable
private fun DatabaseActionButtons(
    onRunBenchmark: () -> Unit,
    isLoading: Boolean,
    isReady: Boolean
) {
    Column(
        verticalArrangement = Arrangement.spacedBy(12.dp)
    ) {
        // Run Full Benchmark Button
        ElevatedButton(
            onClick = onRunBenchmark,
            enabled = !isLoading && isReady,
            modifier = Modifier.fillMaxWidth()
        ) {
            Icon(
                imageVector = Icons.Default.PlayArrow,
                contentDescription = null
            )
            Spacer(modifier = Modifier.width(8.dp))
            Text("Run Full Database Benchmark")
        }

        // Show explanation when not ready
        if (!isReady && !isLoading) {
            Text(
                text = "Please generate notes first using the configuration section above",
                style = MaterialTheme.typography.bodySmall,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
                modifier = Modifier.padding(top = 4.dp)
            )
        }
    }
}

@Composable
private fun BenchmarkResultsSection(
    results: List<DatabaseBenchmarkResult>,
    modifier: Modifier = Modifier
) {
    Column(modifier = modifier) {
        Text(
            text = "Benchmark Results",
            style = MaterialTheme.typography.titleLarge,
            fontWeight = FontWeight.Bold,
            modifier = Modifier.padding(bottom = 8.dp)
        )

        LazyColumn(
            verticalArrangement = Arrangement.spacedBy(8.dp)
        ) {
            items(results) { result ->
                BenchmarkResultCard(result = result)
            }
        }
    }
}

@Composable
private fun BenchmarkResultCard(result: DatabaseBenchmarkResult) {
    Card(
        modifier = Modifier.fillMaxWidth(),
        elevation = CardDefaults.cardElevation(defaultElevation = 4.dp)
    ) {
        Column(
            modifier = Modifier.padding(16.dp)
        ) {
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Text(
                    text = result.operation,
                    style = MaterialTheme.typography.titleMedium,
                    fontWeight = FontWeight.Bold
                )

                Text(
                    text = result.status,
                    style = MaterialTheme.typography.bodySmall,
                    color = if (result.status == "Success") Color.Green else Color.Red
                )
            }

            Spacer(modifier = Modifier.height(8.dp))

            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween
            ) {
                Column {
                    Text(
                        text = "Duration",
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                    Text(
                        text = "${result.duration}ms",
                        style = MaterialTheme.typography.bodyLarge,
                        fontWeight = FontWeight.Medium
                    )
                }

                Column(horizontalAlignment = Alignment.End) {
                    Text(
                        text = "Records",
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                    Text(
                        text = "${result.recordCount}",
                        style = MaterialTheme.typography.bodyLarge,
                        fontWeight = FontWeight.Medium
                    )
                }
            }
        }
    }
}

@Composable
private fun ErrorCard(
    message: String,
    onDismiss: () -> Unit
) {
    Card(
        modifier = Modifier.fillMaxWidth(),
        colors = CardDefaults.cardColors(
            containerColor = MaterialTheme.colorScheme.errorContainer
        )
    ) {
        Row(
            modifier = Modifier
                .fillMaxWidth()
                .padding(16.dp),
            horizontalArrangement = Arrangement.SpaceBetween,
            verticalAlignment = Alignment.CenterVertically
        ) {
            Text(
                text = message,
                style = MaterialTheme.typography.bodyMedium,
                color = MaterialTheme.colorScheme.onErrorContainer,
                modifier = Modifier.weight(1f)
            )

            OutlinedButton(onClick = onDismiss) {
                Text("Dismiss")
            }
        }
    }
}

